package io.sindri.generator.ast.event;

import io.sindri.generator.abstract_.AstFileGenerator;
import io.sindri.generator.enum_.GenerateStatus;
import io.sindri.generator.event.contract.EventDataFileGeneratorContract;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.SequencedSet;

public class AstEventDataFileGenerator extends AstFileGenerator
        implements EventDataFileGeneratorContract {

    /** The largest number of entries {@code Map.of} takes. */
    private static final int MAP_OF_LIMIT = 10;

    /** The one non-printable ASCII character above the control range. */
    private static final char DELETE = 0x7F;

    @Override
    public GenerateStatus generateFile(
            String directory,
            String className,
            String namespace,
            Map<String, String> listeners,
            Map<String, SequencedSet<String>> events) {
        String contents =
                buildFileContents(
                        namespace,
                        className,
                        buildEventsBody(events),
                        buildListenersBody(listeners));
        return writeFile(directory, className, contents);
    }

    protected String buildFileContents(
            String namespace, String className, String eventsBody, String listenersBody) {
        return """
                /*
                 * This file was automatically generated by Sindri.
                 * Do not edit manually.
                 */

                package %NAMESPACE%;

                import io.valkyrja.event.data.contract.EventDataContract;
                import io.valkyrja.event.data.contract.ListenerContract;

                import java.util.Map;

                public record %CLASSNAME%() implements EventDataContract {

                    @Override
                    public Map<Class<?>, Map<String, String>> events() {
                        %EVENTS%
                    }

                    @Override
                    public Map<String, ListenerContract> listeners() {
                        %LISTENERS%
                    }
                }
                """
                .replace("%NAMESPACE%", namespace)
                .replace("%CLASSNAME%", className)
                .replace("%EVENTS%", eventsBody)
                .replace("%LISTENERS%", listenersBody);
    }

    @Override
    public String generateClassContents(Map<String, String> listeners) {
        return buildListenersBody(listeners);
    }

    /**
     * Render an {@code events()} method body from an event class to listener names index. The
     * runtime collection indexes a listener's name under its event class, and a cached listener the
     * index leaves out never fires.
     */
    protected String buildEventsBody(Map<String, SequencedSet<String>> events) {
        List<String> entries = new ArrayList<>();

        events.forEach(
                (eventId, listenerIds) ->
                        entries.add(eventId + ".class, " + buildListenerIdsMap(listenerIds)));

        return buildMapBody(entries);
    }

    protected String buildListenersBody(Map<String, String> listeners) {
        List<String> entries = new ArrayList<>();

        listeners.forEach((name, listener) -> entries.add("\"" + escape(name) + "\", " + listener));

        return buildMapBody(entries);
    }

    /**
     * Render the inline name to name map the runtime collection holds for one event class. The map
     * preserves the order the listeners were registered in, because the dispatcher runs them in
     * iteration order and a stoppable event lets an earlier listener stop a later one. {@code
     * Map.of} cannot carry that order: its iteration order is salted per run.
     */
    private String buildListenerIdsMap(SequencedSet<String> listenerIds) {
        if (listenerIds.isEmpty()) {
            return "Map.of()";
        }

        List<String> quoted = new ArrayList<>();

        for (String listenerId : listenerIds) {
            quoted.add("\"" + escape(listenerId) + "\"");
        }

        return "java.util.stream.Stream.of("
                + String.join(", ", quoted)
                + ").collect(java.util.stream.Collectors.toMap(listenerId -> listenerId,"
                + " listenerId -> listenerId, (first, second) -> first,"
                + " java.util.LinkedHashMap::new))";
    }

    /**
     * Escape a value for a Java string literal, so a name holding a quote, a backslash or a line
     * break cannot end the literal the generated file wraps it in.
     */
    private String escape(String value) {
        StringBuilder escaped = new StringBuilder();

        for (int index = 0; index < value.length(); index++) {
            escaped.append(escapeCharacter(value.charAt(index)));
        }

        return escaped.toString();
    }

    /**
     * Escape one character for a Java string literal. A control character takes a named or an octal
     * escape, never a {@code \\u} escape: the compiler reads a unicode escape before it reads the
     * literal, so {@code \\u000a} ends the line it sits on.
     */
    private String escapeCharacter(char character) {
        return switch (character) {
            case '\\' -> "\\\\";
            case '"' -> "\\\"";
            case '\b' -> "\\b";
            case '\t' -> "\\t";
            case '\n' -> "\\n";
            case '\f' -> "\\f";
            case '\r' -> "\\r";
            default ->
                    character < ' ' || character == DELETE
                            ? String.format("\\%03o", (int) character)
                            : String.valueOf(character);
        };
    }

    /**
     * Render a {@code return} statement for a map literal from already-rendered {@code key, value}
     * entries: an inline {@code Map.of(...)} for up to ten entries, or {@code Map.ofEntries(...)}
     * beyond.
     */
    private String buildMapBody(List<String> entries) {
        if (entries.isEmpty()) {
            return "return Map.of();";
        }

        boolean inline = entries.size() <= MAP_OF_LIMIT;
        StringBuilder body =
                new StringBuilder(inline ? "return Map.of(\n" : "return Map.ofEntries(\n");

        for (int i = 0; i < entries.size(); i++) {
            String entry = entries.get(i);
            body.append("            ").append(inline ? entry : "Map.entry(" + entry + ")");

            if (i < entries.size() - 1) {
                body.append(",");
            }

            body.append("\n");
        }

        return body.append("        );").toString();
    }
}
